// Нормализуем: каждый глиф → массив из 9 строк по 5 символов.
export const GLYPH_W = 5;
export const GLYPH_H = 9;
export const CELL_W = 6;
export const CELL_H = 9;

export const GLYPHS = {};
for (const ch in G) {
  const rows = G[ch].split(/\s+/).filter(Boolean);
  const out = [];
  for (let y = 0; y < GLYPH_H; y++) {
    const row = rows[y] || '.....';
    out.push(row.padEnd(GLYPH_W, '.').slice(0, GLYPH_W));
  }
  GLYPHS[ch] = out;
}

